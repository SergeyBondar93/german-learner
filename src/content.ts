import { Exercise, Level, Topic } from './types';
import { createOptions, normalizeWord, tokenize } from './trainer';

type TopicDraft = Omit<Topic, 'exercises'> & {
  sentences: [prompt: string, answer: string][];
  distractors: string[];
};

function buildTopic(draft: TopicDraft): Topic {
  const exercises: Exercise[] = draft.sentences.map(([prompt, answer], index) => {
    const answerWords = tokenize(answer);
    const distractors = rotateDistractors(draft.distractors, index, answerWords);
    return {
      id: `${draft.id}-${index + 1}`,
      prompt,
      answer,
      options: shuffle(createOptions(answer, distractors), index),
    };
  });

  const { sentences: _sentences, distractors: _distractors, ...topic } = draft;
  return { ...topic, exercises };
}

function rotateDistractors(
  bank: string[],
  offset: number,
  answerWords: string[],
): string[] {
  const answerSet = new Set(answerWords.map(normalizeWord));
  const candidates = bank.filter(
    (word) => !answerSet.has(normalizeWord(word)),
  );
  const rotated = [...candidates.slice(offset % candidates.length), ...candidates.slice(0, offset % candidates.length)];
  return rotated.slice(0, answerWords.length);
}

function shuffle(words: string[], seed: number): string[] {
  const result = [...words];
  let state = seed + 1;
  for (let index = result.length - 1; index > 0; index -= 1) {
    state = (state * 9301 + 49297) % 233280;
    const swapIndex = Math.floor((state / 233280) * (index + 1));
    [result[index], result[swapIndex]] = [result[swapIndex], result[index]];
  }
  return result;
}

